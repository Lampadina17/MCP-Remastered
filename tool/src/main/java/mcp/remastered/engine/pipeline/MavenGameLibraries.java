package mcp.remastered.engine.pipeline;

import mcp.remastered.engine.mojang.VersionJson;
import mcp.remastered.engine.network.CompileDependencies;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.Node;
import org.xml.sax.SAXException;

import javax.xml.XMLConstants;
import javax.xml.parsers.DocumentBuilderFactory;
import javax.xml.parsers.ParserConfigurationException;
import javax.xml.transform.OutputKeys;
import javax.xml.transform.TransformerException;
import javax.xml.transform.TransformerFactory;
import javax.xml.transform.dom.DOMSource;
import javax.xml.transform.stream.StreamResult;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

/**
 * Maintains a dedicated Maven profile pointing at the downloaded game libraries.
 */
public final class MavenGameLibraries {
    private static final String PROFILE = "mcp-remastered-game-libraries";
    private static final String MARKER = "Generated by MCP Remastered; changes inside this profile are replaced.";

    private MavenGameLibraries() {
    }

    public static int update(Path pom, VersionJson version, List<Path> downloaded, List<Path> compileOnly) throws IOException {
        return update(pom, pom.toAbsolutePath().getParent(), version, downloaded, compileOnly);
    }

    public static int update(Path pom, Path workspace, VersionJson version, List<Path> downloaded, List<Path> compileOnly) throws IOException {
        try {
            DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
            factory.setNamespaceAware(true);
            factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true);
            factory.setAttribute(XMLConstants.ACCESS_EXTERNAL_DTD, "");
            factory.setAttribute(XMLConstants.ACCESS_EXTERNAL_SCHEMA, "");
            Document doc = factory.newDocumentBuilder().parse(pom.toFile());
            Element project = doc.getDocumentElement();
            if (!"project".equals(project.getLocalName())) throw new IOException("Not a Maven project: " + pom);
            Element profiles = child(project, "profiles");
            if (profiles == null) profiles = add(project, "profiles", null);
            Element old = null;
            for (Node node = profiles.getFirstChild(); node != null; node = node.getNextSibling()) {
                if (node instanceof Element e && "profile".equals(e.getLocalName()) && PROFILE.equals(text(e, "id"))) {
                    if (old != null || !hasMarker(e))
                        throw new IOException("Maven profile " + PROFILE + " already exists and is not managed by MCP Remastered");
                    old = e;
                }
            }
            if (old != null) profiles.removeChild(old);
            Element profile = add(profiles, "profile", null);
            profile.appendChild(doc.createComment(MARKER));
            add(profile, "id", PROFILE);
            Element activation = add(profile, "activation", null);
            Element property = add(activation, "property", null);
            add(property, "name", "!mcp.disableGameLibraries");
            Element dependencies = add(profile, "dependencies", null);
            Set<String> used = new HashSet<>();
            Element existing = child(project, "dependencies");
            if (existing != null) for (Node n = existing.getFirstChild(); n != null; n = n.getNextSibling()) {
                if (n instanceof Element e && "dependency".equals(e.getLocalName()))
                    used.add(key(text(e, "groupId"), text(e, "artifactId"), text(e, "classifier")));
            }
            Set<Path> files = new HashSet<>();
            for (Path p : downloaded) files.add(p.toAbsolutePath().normalize());
            int count = 0;
            if (version.libraries != null) for (VersionJson.Library lib : version.libraries) {
                if (lib.name == null || lib.downloads == null || lib.downloads.artifact == null || lib.downloads.artifact.path == null)
                    continue;
                Path file = workspace.toAbsolutePath().resolve("runtime/libraries").resolve(lib.downloads.artifact.path).normalize();
                if (files.contains(file) && addDependency(dependencies, pom, workspace, lib.name, file, used)) count++;
            }
            for (int i = 0; i < Math.min(compileOnly.size(), CompileDependencies.coordinates().size()); i++) {
                if (addDependency(dependencies, pom, workspace, CompileDependencies.coordinates().get(i), compileOnly.get(i), used))
                    count++;
            }
            if (old != null && sameGeneratedProfile(old, profile)) return count;
            indentGenerated(profile, 2);
            TransformerFactory tf = TransformerFactory.newInstance();
            tf.setAttribute(XMLConstants.ACCESS_EXTERNAL_DTD, "");
            tf.setAttribute(XMLConstants.ACCESS_EXTERNAL_STYLESHEET, "");
            var transformer = tf.newTransformer();
            transformer.setOutputProperty(OutputKeys.ENCODING, "UTF-8");
            transformer.setOutputProperty(OutputKeys.INDENT, "no");
            Path temp = Files.createTempFile(pom.toAbsolutePath().getParent(), "pom-game-libraries-", ".xml");
            try {
                transformer.transform(new DOMSource(doc), new StreamResult(temp.toFile()));
                Files.move(temp, pom, StandardCopyOption.REPLACE_EXISTING);
            } finally {
                Files.deleteIfExists(temp);
            }
            return count;
        } catch (ParserConfigurationException | SAXException | TransformerException | IllegalArgumentException e) {
            throw new IOException("Cannot update Maven POM " + pom, e);
        }
    }

    private static boolean addDependency(Element parent, Path pom, Path workspace, String coordinate, Path file, Set<String> used) throws IOException {
        String[] parts = coordinate.split(":", -1);
        if (parts.length < 3 || parts.length > 4 || parts[0].isBlank() || parts[1].isBlank() || parts[2].isBlank())
            throw new IOException("Unsupported library coordinates: " + coordinate);
        String classifier = parts.length == 4 ? parts[3] : "";
        Path root = pom.toAbsolutePath().normalize().getParent();
        Path path = file.toAbsolutePath().normalize();
        if (!path.startsWith(workspace.toAbsolutePath().normalize()) || !Files.isRegularFile(path))
            throw new IOException("Missing or external game library: " + path);
        if (!used.add(key(parts[0], parts[1], classifier))) return false;
        Element dep = add(parent, "dependency", null);
        add(dep, "groupId", parts[0]);
        add(dep, "artifactId", parts[1]);
        add(dep, "version", parts[2]);
        if (!classifier.isEmpty()) add(dep, "classifier", classifier);
        add(dep, "scope", "system");
        add(dep, "systemPath", "${project.basedir}/" + root.relativize(path).toString().replace('\\', '/'));
        return true;
    }

    private static String key(String group, String artifact, String classifier) {
        return group + ":" + artifact + ":" + classifier;
    }

    private static Element child(Element parent, String name) {
        for (Node n = parent.getFirstChild(); n != null; n = n.getNextSibling())
            if (n instanceof Element e && name.equals(e.getLocalName())) return e;
        return null;
    }

    private static String text(Element parent, String name) {
        Element e = child(parent, name);
        return e == null ? "" : e.getTextContent().trim();
    }

    private static boolean hasMarker(Element parent) {
        for (Node n = parent.getFirstChild(); n != null; n = n.getNextSibling())
            if (n.getNodeType() == Node.COMMENT_NODE && MARKER.equals(n.getNodeValue())) return true;
        return false;
    }

    private static Element add(Element parent, String name, String value) {
        Document doc = parent.getOwnerDocument();
        Element e = doc.createElementNS(parent.getNamespaceURI(), name);
        if (value != null) e.setTextContent(value);
        parent.appendChild(e);
        return e;
    }

    private static void indentGenerated(Element element, int depth) {
        Document doc = element.getOwnerDocument();
        boolean children = false;
        for (Node n = element.getFirstChild(); n != null; ) {
            Node next = n.getNextSibling();
            if (n instanceof Element || n.getNodeType() == Node.COMMENT_NODE) {
                children = true;
                element.insertBefore(doc.createTextNode("\n" + "  ".repeat(depth + 1)), n);
                if (n instanceof Element child) indentGenerated(child, depth + 1);
            }
            n = next;
        }
        if (children) element.appendChild(doc.createTextNode("\n" + "  ".repeat(depth)));
    }

    private static boolean sameGeneratedProfile(Element old, Element current) {
        Node previous = old.cloneNode(true);
        removeWhitespace(previous);
        Node generated = current.cloneNode(true);
        removeWhitespace(generated);
        return previous.isEqualNode(generated);
    }

    private static void removeWhitespace(Node node) {
        for (Node child = node.getFirstChild(); child != null; ) {
            Node next = child.getNextSibling();
            if (child.getNodeType() == Node.TEXT_NODE && child.getNodeValue().isBlank()) node.removeChild(child);
            else removeWhitespace(child);
            child = next;
        }
    }
}
